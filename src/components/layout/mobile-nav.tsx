export function MobileNav() {
  const pathname = usePathname();

  return (
    <nav
      className="lg:hidden fixed bottom-0 inset-x-0 z-30 bg-white border-t border-slate-200"
      aria-label="Mobile navigation"
    >
      <div className="flex items-stretch h-16 safe-area-bottom">
        {navItems.map((item) => {
          const isActive =
            pathname === item.href || pathname.startsWith(item.href + "/");
          return (
            <Link
              key={item.href}
              href={item.href}
              className={`flex flex-col items-center justify-center gap-1 flex-1 min-h-[44px] transition-colors cursor-pointer ${
                isActive ? "text-teal-600" : "text-slate-400 hover:text-slate-600"
              }`}
              aria-current={isActive ? "page" : undefined}
            >
              {item.icon(isActive)}
              <span
                className={`text-xs font-medium leading-none ${
                  isActive ? "text-teal-600" : "text-slate-500"
                }`}
              >
                {item.label}
              </span>
            </Link>
          );
        })}
      </div>
    </nav>
  );
}
